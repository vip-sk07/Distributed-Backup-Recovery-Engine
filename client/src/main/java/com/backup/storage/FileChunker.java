package com.backup.storage;

import com.backup.crypto.HashUtil;
import com.backup.model.Chunk;
import com.backup.model.FileSnapshot;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.channels.FileChannel;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.List;

/**
 * FastCDC Content-Defined Chunking implementation.
 *
 * <p>Uses a Gear rolling hash to find content-based chunk boundaries, solving
 * the "boundary shift problem" of fixed-size chunking. A chunk boundary is
 * declared when {@code (hash & mask) == 0}.
 *
 * <p>Parameters:
 * <ul>
 *   <li>MIN_SIZE  = 16 KB</li>
 *   <li>AVG_SIZE  = 64 KB (target average)</li>
 *   <li>MAX_SIZE  = 256 KB (hard ceiling)</li>
 *   <li>MASK_S    used for positions in [MIN_SIZE, 2*AVG_SIZE)</li>
 *   <li>MASK_L    used for positions in [2*AVG_SIZE, MAX_SIZE)</li>
 * </ul>
 *
 * <p>Reference: Xia et al., "FastCDC: a Fast and Efficient Content-Defined
 * Chunking Approach for Data Deduplication" (USENIX ATC 2016).
 */
public class FileChunker {

    // -----------------------------------------------------------------------
    // FastCDC constants
    // -----------------------------------------------------------------------
    public static final int MIN_SIZE = 16 * 1024;        // 16 KB
    public static final int AVG_SIZE = 64 * 1024;        // 64 KB
    public static final int MAX_SIZE = 256 * 1024;       // 256 KB
    public static final String CHUNKING_MODE = "FastCDC";

    /** Mask used when position ∈ [MIN_SIZE, 2*AVG_SIZE). Fewer zero bits → more boundaries → smaller chunks. */
    private static final long MASK_S = 0x0000_0000_0003_FFFFL;

    /** Mask used when position ∈ [2*AVG_SIZE, MAX_SIZE). More zero bits → fewer boundaries → larger chunks. */
    private static final long MASK_L = 0x0000_0000_0007_FFFFL;

    // -----------------------------------------------------------------------
    // Gear hash table – 256 deterministic 64-bit values.
    // Generated by a linear congruential generator seeded with the constant
    // 0x4A6F686E4B657273L so results are always identical across runs.
    // -----------------------------------------------------------------------
    private static final long[] GEAR_TABLE = new long[256];

    static {
        long state = 0x4A6F686E4B657273L; // seed
        for (int i = 0; i < 256; i++) {
            // LCG: multiplier and addend chosen for good distribution
            state = state * 6364136223846793005L + 1442695040888963407L;
            GEAR_TABLE[i] = state;
        }
    }

    // -----------------------------------------------------------------------
    // Legacy API compatibility
    // -----------------------------------------------------------------------
    public static final int DEFAULT_CHUNK_SIZE = AVG_SIZE; // 64 KB kept for API compat

    /**
     * The constructor {@code chunkSize} parameter is retained for API
     * compatibility. FastCDC ignores it internally; chunk sizes are always
     * determined by content.
     */
    private final int chunkSize;

    public FileChunker(int chunkSize) {
        if (chunkSize <= 0) throw new IllegalArgumentException("Chunk size must be positive: " + chunkSize);
        this.chunkSize = chunkSize;
    }

    public FileChunker() {
        this(DEFAULT_CHUNK_SIZE);
    }

    /** Returns the configured nominal chunk size (legacy / API compat). */
    public int getChunkSize() {
        return chunkSize;
    }

    // -----------------------------------------------------------------------
    // FastCDC core: find where the current chunk ends
    // -----------------------------------------------------------------------

    /**
     * Given a byte array {@code buf} and a starting position {@code from},
     * returns the length of the next chunk (≥ 1, ≤ MAX_SIZE).
     *
     * @param buf       the data buffer
     * @param from      starting index inside {@code buf}
     * @param available number of bytes available starting at {@code from}
     * @return chunk length (number of bytes in this chunk)
     */
    private int findChunkEnd(byte[] buf, int from, int available) {
        int pos = 0; // position within this chunk (0-based)
        long hash = 0L;

        // ---- Phase 0: skip the minimum prefix unconditionally ----
        int minLen = Math.min(MIN_SIZE, available);
        while (pos < minLen) {
            hash = (hash << 1) + GEAR_TABLE[buf[from + pos] & 0xFF];
            pos++;
        }

        // ---- Phase 1: positions [MIN_SIZE, 2*AVG_SIZE) – use MASK_S ----
        int phase1End = Math.min(2 * AVG_SIZE, available);
        while (pos < phase1End) {
            hash = (hash << 1) + GEAR_TABLE[buf[from + pos] & 0xFF];
            pos++;
            if ((hash & MASK_S) == 0L) {
                return pos; // boundary found
            }
        }

        // ---- Phase 2: positions [2*AVG_SIZE, MAX_SIZE) – use MASK_L ----
        int phase2End = Math.min(MAX_SIZE, available);
        while (pos < phase2End) {
            hash = (hash << 1) + GEAR_TABLE[buf[from + pos] & 0xFF];
            pos++;
            if ((hash & MASK_L) == 0L) {
                return pos; // boundary found
            }
        }

        // ---- No boundary found within MAX_SIZE: hard cut ----
        return pos; // == min(MAX_SIZE, available)
    }

    // -----------------------------------------------------------------------
    // Main public API: chunk a file and return a FileSnapshot
    // -----------------------------------------------------------------------

    private static final int READ_BUFFER_SIZE = 2 * 1024 * 1024; // 2 MB I/O buffer

    /**
     * Chunks {@code filePath} using FastCDC and returns a {@link FileSnapshot}
     * containing metadata and chunk list.
     *
     * @param rootDir             the root directory (used to compute relative paths)
     * @param filePath            the file to chunk
     * @param includeDataInMemory if {@code true}, each {@link Chunk} carries its raw bytes
     * @return a fully populated {@link FileSnapshot}
     * @throws IOException on I/O errors
     */
    public FileSnapshot chunkFile(Path rootDir, Path filePath, boolean includeDataInMemory) throws IOException {
        Path relativePath = rootDir.relativize(filePath);
        String relPathStr = relativePath.toString().replace('\\', '/');
        long fileSize = Files.size(filePath);
        long lastModified = Files.getLastModifiedTime(filePath).toMillis();
        String fileId = HashUtil.sha256Hex(relPathStr.getBytes()).substring(0, 16);

        MessageDigest wholeFileDigest = HashUtil.getSha256Digest();
        List<Chunk> chunkList = new ArrayList<>();

        // Handle empty files
        if (fileSize == 0) {
            String emptyHash = HashUtil.toHex(wholeFileDigest.digest());
            return new FileSnapshot(fileId, relPathStr, 0, lastModified, emptyHash, chunkList);
        }

        try (FileChannel channel = FileChannel.open(filePath, StandardOpenOption.READ)) {
            ByteBuffer ioBuf = ByteBuffer.allocateDirect(READ_BUFFER_SIZE);

            // "pending" holds leftover bytes from the previous read that haven't
            // been assigned to a chunk yet (they sit at the start of the working buffer).
            byte[] pending = new byte[MAX_SIZE];
            int pendingLen = 0;

            long currentOffset = 0L; // byte offset of the start of the current chunk within the file
            int chunkIndex = 0;
            boolean eof = false;

            while (!eof || pendingLen > 0) {
                // ---- Read more data from the channel into pending ----
                if (!eof) {
                    ioBuf.clear();
                    int bytesRead = channel.read(ioBuf);
                    if (bytesRead <= 0) {
                        eof = true;
                    } else {
                        ioBuf.flip();
                        // Ensure pending[] is large enough (it could be up to MAX_SIZE + READ_BUFFER_SIZE)
                        int needed = pendingLen + bytesRead;
                        if (needed > pending.length) {
                            byte[] bigger = new byte[needed + MAX_SIZE];
                            System.arraycopy(pending, 0, bigger, 0, pendingLen);
                            pending = bigger;
                        }
                        ioBuf.get(pending, pendingLen, bytesRead);
                        pendingLen += bytesRead;
                    }
                }

                // ---- Slice chunks out of pending[] ----
                // We can safely cut chunks when:
                //   (a) we're at EOF → emit everything left as final chunk(s), or
                //   (b) we have at least MAX_SIZE bytes → findChunkEnd can run to completion
                while (pendingLen > 0 && (eof || pendingLen >= MAX_SIZE)) {
                    int chunkLen = findChunkEnd(pending, 0, pendingLen);

                    // Update whole-file digest
                    wholeFileDigest.update(pending, 0, chunkLen);

                    // Hash this chunk's bytes
                    String chunkHash = HashUtil.sha256Hex(pending, 0, chunkLen);

                    // Optionally keep data in memory
                    byte[] chunkData = null;
                    if (includeDataInMemory) {
                        chunkData = new byte[chunkLen];
                        System.arraycopy(pending, 0, chunkData, 0, chunkLen);
                    }

                    chunkList.add(new Chunk(chunkIndex++, currentOffset, chunkLen, chunkHash, chunkData));
                    currentOffset += chunkLen;

                    // Shift remaining bytes to the front of pending[]
                    pendingLen -= chunkLen;
                    if (pendingLen > 0) {
                        System.arraycopy(pending, chunkLen, pending, 0, pendingLen);
                    }
                }
            }
        }

        String wholeFileHash = HashUtil.toHex(wholeFileDigest.digest());
        return new FileSnapshot(fileId, relPathStr, fileSize, lastModified, wholeFileHash, chunkList);
    }
}
